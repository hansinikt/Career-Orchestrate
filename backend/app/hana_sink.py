"""Optional mirror of the agent activity log to SAP HANA Cloud.
SQLite stays the source of truth. This module only COPIES each log line to a HANA table, and only when the HANA settings below are present.
If they are missing, or HANA is stopped or unreachable, nothing happens and the app carries on (same idea as the Gemini fallback).
Settings (environment variables, never committed): HANA_HOST, HANA_USER, HANA_PASSWORD, optional HANA_PORT (default 443), HANA_SCHEMA.
What is sent: the same short summaries the dashboard already shows ("12 confirmed skills (no age, gender or years used)"), the agent name and a time. No names, no CV text.
"""
import logging, os, threading, time
log = logging.getLogger("hana")
TABLE = "CO_AGENT_TRACE"
_lock = threading.Lock()
_conn = None
_ready = False                 # table checked or created
_down_until = 0.0              # after a failure, skip HANA for a minute
_last_ok = None

def enabled() -> bool:
    return all(os.environ.get(k) for k in ("HANA_HOST", "HANA_USER", "HANA_PASSWORD"))

def _connect():
    global _conn
    from hdbcli import dbapi   # imported here so the app runs without the library when HANA is not used
    _conn = dbapi.connect(address=os.environ["HANA_HOST"], port=int(os.environ.get("HANA_PORT", "443")), user=os.environ["HANA_USER"],
                          password=os.environ["HANA_PASSWORD"], encrypt=True, sslValidateCertificate=True, connectTimeout=5000, communicationTimeout=8000)
    schema = os.environ.get("HANA_SCHEMA")
    if schema:
        cur = _conn.cursor(); cur.execute('SET SCHEMA "%s"' % schema.replace('"', "")); cur.close()
    return _conn

def _ensure_table(conn):
    global _ready
    if _ready: return
    cur = conn.cursor()
    try:
        cur.execute(f"CREATE TABLE {TABLE} (ID BIGINT GENERATED BY DEFAULT AS IDENTITY, PROFILE_ID NVARCHAR(40), AGENT NVARCHAR(40), MODE NVARCHAR(60), "
                    "INPUT_SUMMARY NVARCHAR(200), OUTPUT_SUMMARY NVARCHAR(200), STOPPED_AT_GATE TINYINT, CREATED_AT NVARCHAR(40), PRIMARY KEY (ID))")
        conn.commit()
    except Exception as e:
        if "288" not in str(e) and "duplicate table name" not in str(e).lower(): raise     # 288 = the table already exists, which is fine
    finally: cur.close()
    _ready = True

def _write(row: dict) -> bool:
    """Write one log line. Returns True if it reached HANA. Never raises."""
    global _conn, _down_until, _last_ok
    if not enabled() or time.time() < _down_until: return False
    try:
        with _lock:
            conn = _conn or _connect()
            _ensure_table(conn)
            cur = conn.cursor()
            cur.execute(f"INSERT INTO {TABLE} (PROFILE_ID, AGENT, MODE, INPUT_SUMMARY, OUTPUT_SUMMARY, STOPPED_AT_GATE, CREATED_AT) VALUES (?,?,?,?,?,?,?)",
                        (row["profile_id"], row["agent"], row["mode"], row["input_summary"], row["output_summary"], 1 if row.get("stopped_at_gate") else 0, row["created_at"]))
            conn.commit(); cur.close()
        _last_ok = row["created_at"]
        return True
    except Exception as e:
        log.warning("HANA mirror skipped: %s", str(e)[:160])
        _down_until = time.time() + 60
        with _lock:
            try:
                if _conn: _conn.close()
            except Exception: pass
            _conn = None
        return False

def mirror(row: dict) -> None:
    """Called after every log line is saved in SQLite. Returns at once; the copy to HANA runs in the background."""
    if not enabled(): return
    threading.Thread(target=_write, args=(dict(row),), daemon=True).start()

def status() -> dict:
    return dict(enabled=enabled(), last_written=_last_ok, paused=time.time() < _down_until)
